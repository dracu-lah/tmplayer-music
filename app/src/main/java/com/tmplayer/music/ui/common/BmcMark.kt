/**
 * Buy Me a Coffee's own colours, from their brand kit (https://buymeacoffee.com/brand): the yellow
 * every one of their buttons is filled with, and the near-black their words and cup are drawn in.
 * Their mark is only ever shown on the yellow, as they show it, and the words on it are the ink.
 */
object BmcBrand {
    val Yellow = Color(0xFFFFDD00)
    val Ink = Color(0xFF0D0C22)
}

/**
 * Buy Me a Coffee's cup, the official artwork: the 14 paths of the cup in "SVG Files/bmc-button.svg"
 * from their brand kit, taken unchanged from TMPlayer (`ui/about/BmcMark.kt`, same author), as the
 * site's `public/brand/bmc-cup-on-yellow.svg` has them, inside the same tighter frame (x 47.5 to 117.5, y 26.5 to 126.5). The coffee is white and
 * the cup the ink, meant for the yellow. Buy Me a Coffee is a trademark of its owner.
 */
val BmcCup: ImageVector by lazy {
    ImageVector.Builder(
        name = "BmcCup",
        defaultWidth = 14.dp,
        defaultHeight = 20.dp,
        viewportWidth = 70f,
        viewportHeight = 100f,
    ).apply {
        group(translationX = -47.5f, translationY = -26.5f) {
            for ((colour, data) in CUP_PATHS) addPath(addPathNodes(data), fill = SolidColor(colour))
        }
    }.build()
}

/** The cup at [height], always drawn on [BmcBrand.Yellow] by whoever places it. */
@Composable
fun BmcCupMark(modifier: Modifier = Modifier, height: Dp = 20.dp) {
    Image(BmcCup, contentDescription = null, modifier = modifier.size(width = height * 0.7f, height = height))
}

