    /** A full circle of radius [r] at ([x], [y]), for holes cut out of a filled shape. */
    private fun ring(x: Float, y: Float, r: Float): String {
        val k = r * 0.5523f
        return "M${x + r} ${y}C${x + r} ${y + k} ${x + k} ${y + r} $x ${y + r}" +
            "C${x - k} ${y + r} ${x - r} ${y + k} ${x - r} ${y}" +
            "C${x - r} ${y - k} ${x - k} ${y - r} $x ${y - r}" +
            "C${x + k} ${y - r} ${x + r} ${y - k} ${x + r} ${y}Z"
    }

