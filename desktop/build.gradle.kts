// TMPlayer Music for Windows, Linux and macOS: a Compose Desktop front end over :core, playing
// through libmpv (mediamp). The setup follows ../TMPlayer/desktop/build.gradle.kts (GPL-3.0), left
// out until a later task: the AppImage and DMG packaging and the TDLib jar trimming.

plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.compose.multiplatform)
}

// A full JDK 21 (with AWT's desktop half: Fedora's java-25-openjdk-headless cannot open a window),
// as ../TMPlayer's desktop builds with. Bytecode stays at 17, like :core.
kotlin {
    jvmToolchain(21)
    compilerOptions.jvmTarget.set(JvmTarget.JVM_17)
}
tasks.withType<JavaCompile>().configureEach {
    sourceCompatibility = "17"
    targetCompatibility = "17"
}

val desktopVersion: String = providers.gradleProperty("desktopVersion").getOrElse("0.1.0-dev")

// The installer version jpackage wants: a plain x.y.z from the version asked for (-PdesktopVersion=1.2.3-beta.1 gives 1.2.3).
// An MSI, a deb and a macOS bundle all refuse anything else; 0.1.0 is the development build's.
val packageVersionName: String = desktopVersion.removePrefix("v").substringBefore('-').substringBefore('+')
    .takeIf { Regex("""\d+\.\d+\.\d+""").matches(it) } ?: "0.1.0"
val packagingDir = layout.projectDirectory.dir("packaging")

// The same local.properties the Android build reads, for the same Telegram API credentials.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

// Credentials and version reach the app as a generated object, the desktop's BuildConfig.
val generateBuildInfo = tasks.register("generateBuildInfo") {
    val out = layout.buildDirectory.dir("generated/buildinfo")
    val apiId = localProps.getProperty("TG_API_ID") ?: "0"
    val apiHash = localProps.getProperty("TG_API_HASH") ?: ""
    inputs.property("apiId", apiId)
    inputs.property("apiHash", apiHash)
    inputs.property("version", desktopVersion)
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.resolve("com/tmplayer/music/desktop").apply { mkdirs() }
        dir.resolve("BuildInfo.kt").writeText(
            """
            |package com.tmplayer.music.desktop
            |
            |// Generated by :desktop's generateBuildInfo. Do not edit.
            |internal object BuildInfo {
            |    const val VERSION = "$desktopVersion"
            |    const val TG_API_ID = ${apiId.toIntOrNull() ?: 0}
            |    const val TG_API_HASH = "${apiHash.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")}"
            |}
            |
            """.trimMargin(),
        )
    }
}
kotlin.sourceSets.main { kotlin.srcDir(generateBuildInfo) }

val hostOs: String = System.getProperty("os.name").lowercase()
val hostMac: Boolean = hostOs.contains("mac")
val mpvRuntime = when {
    hostOs.contains("win") -> libs.mediamp.runtime.windows.x64
    // Apple Silicon only, as in TMPlayer: Intel Macs are not offered.
    hostMac -> libs.mediamp.runtime.macos.arm64
    else -> libs.mediamp.runtime.linux.x64
}

